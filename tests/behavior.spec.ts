test('living hero draws continuously while offscreen journey rests and reacts to native scroll',async({page})=>{
 await page.goto('/')
 const graph=page.getByTestId('execution-graph-canvas')
 await graph.scrollIntoViewIfNeeded()
 await expect(graph).toHaveAttribute('data-ready','true')
 await expect(graph).toHaveAttribute('data-phase','settled',{timeout:12000});await page.waitForTimeout(200)
 const count=async()=>Number(await graph.getAttribute('data-draw-count'))
 const idle=await count();await page.waitForTimeout(1000);expect(await count()-idle).toBeGreaterThan(1)
 await page.evaluate(()=>window.scrollBy({top:120,behavior:'instant'}))
 await expect.poll(count).toBeGreaterThan(idle)
 await page.evaluate(()=>window.scrollTo({top:document.body.scrollHeight,behavior:'instant'}))
 await expect(graph).toHaveAttribute('data-word','1')
 const off=await count();await page.waitForTimeout(600);expect(await count()).toBe(off)
})
