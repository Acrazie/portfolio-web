import AxeBuilder from '@axe-core/playwright'
import { expect,test } from '@playwright/test'
test('accessible French page fits the viewport, switches language, and supports keyboard anchors',async({page,isMobile})=>{
 await page.goto('/')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)).toBeLessThanOrEqual(1)
 expect((await new AxeBuilder({page}).analyze()).violations).toEqual([])
 await expect(page).toHaveTitle('Mayeul — Software Engineer · AI Engineer')
 await expect(page.locator('html')).toHaveAttribute('lang','fr')
 await page.keyboard.press('Tab');await expect(page.getByRole('link',{name:'Aller au contenu'})).toBeFocused()
 await page.keyboard.press('Enter');await expect(page.locator('#main')).toBeFocused()
 await page.getByRole('link',{name:'Entrer dans le portfolio'}).click();await expect(page).toHaveURL(/#about$/)
 await page.getByRole('button',{name:'Langue : français. Passer en anglais'}).click()
 await expect(page.locator('html')).toHaveAttribute('lang','en')
 if(isMobile)await expect(page.getByRole('navigation',{name:'Primary navigation'})).toBeHidden()
 else await expect(page.getByRole('navigation',{name:'Primary navigation'})).toBeVisible()
})
