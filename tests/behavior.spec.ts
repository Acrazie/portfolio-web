test('pause, hot reduced motion, and hidden pages stop the scene and preserve fallbacks',async({page})=>{
 await page.goto('/');const host=page.getByTestId('logo-particles')
 await expect(page.getByTestId('execution-graph-canvas')).toHaveAttribute('data-phase','settled',{timeout:15000})
 await page.getByRole('button',{name:'Mettre l’animation en pause'}).click()
 await expect(page.getByRole('button',{name:'Reprendre l’animation'})).toBeVisible()
 const pausedCount=await page.getByTestId('execution-graph-canvas').getAttribute('data-draw-count');await page.waitForTimeout(200)
 expect(await page.getByTestId('execution-graph-canvas').getAttribute('data-draw-count')).toBe(pausedCount)
 await page.getByRole('button',{name:'Reprendre l’animation'}).click()
 await expect(host).toHaveCSS('visibility','visible')
 await page.emulateMedia({reducedMotion:'reduce'})
 await expect(page.getByTestId('execution-graph-canvas')).toHaveCount(0)
 await expect(page.getByTestId('execution-graph-fallback')).toBeVisible()
 await page.emulateMedia({reducedMotion:'no-preference'})
 await expect(page.getByTestId('execution-graph-canvas')).toHaveAttribute('data-ready','true')
 await page.evaluate(()=>{Object.defineProperty(document,'visibilityState',{configurable:true,value:'hidden'});document.dispatchEvent(new Event('visibilitychange'))})
 await expect(host).toHaveCSS('visibility','visible')
 const count=await page.getByTestId('execution-graph-canvas').getAttribute('data-draw-count');await page.waitForTimeout(200)
 expect(await page.getByTestId('execution-graph-canvas').getAttribute('data-draw-count')).toBe(count)
})
