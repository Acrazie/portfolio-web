import AxeBuilder from '@axe-core/playwright'
import { expect,test } from '@playwright/test'
test('accessible English page fits the viewport and supports keyboard anchors',async({page})=>{
 await page.goto('/')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)).toBeLessThanOrEqual(1)
 expect((await new AxeBuilder({page}).analyze()).violations).toEqual([])
 await expect(page).toHaveTitle('Acrazie — Software Engineer & AI Engineer')
 await expect(page.locator('html')).toHaveAttribute('lang','en')
 await page.keyboard.press('Tab');await expect(page.getByRole('link',{name:'Skip to content'})).toBeFocused()
 await page.keyboard.press('Enter');await expect(page.locator('#main')).toBeFocused()
 await page.getByRole('link',{name:'Contact',exact:true}).click();await expect(page).toHaveURL(/#contact$/)
})
