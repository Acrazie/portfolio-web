test('hot reduced motion, pause and hidden clear impulses without remounting the canvas',async({page})=>{
 await page.goto('/');const graph=page.getByTestId('execution-graph-canvas'),host=page.getByTestId('logo-particles')
 await expect(graph).toHaveAttribute('data-phase','settled',{timeout:15000})
 const node=await graph.locator('canvas').elementHandle()
 for(const mode of ['reduce','pause','hidden']){
  if(mode==='reduce')await page.emulateMedia({reducedMotion:'reduce'})
  if(mode==='pause')await page.getByRole('button',{name:'Pause animation'}).click()
  if(mode==='hidden')await page.evaluate(()=>{Object.defineProperty(document,'visibilityState',{configurable:true,value:'hidden'});document.dispatchEvent(new Event('visibilitychange'))})
  await expect(host).toHaveCSS('visibility','hidden');await expect(page.getByTestId('execution-graph-fallback')).toBeVisible()
  await page.waitForTimeout(100);const count=await graph.getAttribute('data-draw-count')
  await page.evaluate(()=>scrollTo({top:document.documentElement.scrollHeight,behavior:'instant'}));await page.waitForTimeout(150)
  expect(await graph.getAttribute('data-draw-count')).toBe(count);await expect(page.getByTestId('particle-word')).not.toHaveCSS('color','rgba(0, 0, 0, 0)')
  if(mode==='reduce')await page.emulateMedia({reducedMotion:'no-preference'})
  if(mode==='pause')await page.getByRole('button',{name:'Resume animation'}).click()
  if(mode==='hidden')await page.evaluate(()=>{Object.defineProperty(document,'visibilityState',{configurable:true,value:'visible'});document.dispatchEvent(new Event('visibilitychange'))})
  await expect(graph).toHaveAttribute('data-word','1');await expect(host).toHaveCSS('visibility','visible')
  expect(await node!.evaluate(c=>c===document.querySelector('canvas'))).toBe(true)
  await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));await expect(graph).toHaveAttribute('data-split','0')
 }
})
